#!/usr/bin/env node
// Render mappings/ASVS-5.0.md from the official requirement list + our mapping. Zero deps.
//   node mappings/render-asvs.mjs            (reads asvs-5.0.0.flat.json + asvs-map.json in this folder)
// asvs-map.json: [{ req_id, L, status: covered|partial|gap|n/a, rules: [...], note, proposed }]
// Re-run after editing asvs-map.json (e.g. when a new rule closes a gap: set status + rules, clear proposed).
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const asvs = JSON.parse(readFileSync(join(here, 'asvs-5.0.0.flat.json'), 'utf8')).requirements
const map = new Map(JSON.parse(readFileSync(join(here, 'asvs-map.json'), 'utf8')).map(m => [m.req_id, m]))
const missing = asvs.filter(r => !map.has(r.req_id))
if (missing.length) { console.error(`✗ ${missing.length} requirements unmapped: ${missing.slice(0, 5).map(r => r.req_id).join(', ')}…`); process.exit(1) }

const STATUSES = ['covered', 'partial', 'gap', 'n/a']
const ICON = { covered: '✅', partial: '🟡', gap: '🔴', 'n/a': '—' }
const esc = (s) => String(s || '').replace(/\|/g, '\\|').replace(/\n/g, ' ')
const pct = (n, d) => d ? `${Math.round(100 * n / d)}%` : '–'
const rows = asvs.map(r => ({ ...r, ...map.get(r.req_id) }))
const tally = (list) => Object.fromEntries(STATUSES.map(s => [s, list.filter(r => r.status === s).length]))
const atLevel = (lv) => rows.filter(r => +r.L <= lv)

const out = []
out.push('# OWASP ASVS 5.0 → Engineering Standard mapping', '',
  `Every one of the ${asvs.length} ASVS 5.0.0 requirements mapped to the rule IDs in`,
  '[ENGINEERING_STANDARD.md](../ENGINEERING_STANDARD.md). Generated by `mappings/render-asvs.mjs` from',
  '`asvs-map.json` — edit the JSON, not this file.', '',
  '**Status:** ✅ covered — a rule requires it at least as strictly · 🟡 partial — a rule touches it but is',
  'vaguer or narrower · 🔴 gap — nothing requires it · — n/a — does not apply to these apps (reason given).', '')
out.push('## Summary', '', '| Scope | Requirements | ✅ Covered | 🟡 Partial | 🔴 Gap | — n/a | Covered of applicable |', '|---|---|---|---|---|---|---|')
for (const [label, list] of [['Level 1', atLevel(1)], ['Levels 1–2 (our claim)', atLevel(2)], ['All levels (1–3)', rows]]) {
  const t = tally(list), applicable = list.length - t['n/a']
  out.push(`| ${label} | ${list.length} | ${t.covered} | ${t.partial} | ${t.gap} | ${t['n/a']} | **${pct(t.covered, applicable)}** (${pct(t.covered + t.partial, applicable)} incl. partial) |`)
}
out.push('', '### By chapter (Levels 1–2)', '', '| Chapter | Req. | ✅ | 🟡 | 🔴 | — |', '|---|---|---|---|---|---|')
const chapters = [...new Map(rows.map(r => [r.chapter_id, r.chapter_name])).entries()]
for (const [id, name] of chapters) {
  const t = tally(atLevel(2).filter(r => r.chapter_id === id))
  out.push(`| ${id} ${esc(name)} | ${Object.values(t).reduce((a, b) => a + b, 0)} | ${t.covered} | ${t.partial} | ${t.gap} | ${t['n/a']} |`)
}
const open = atLevel(2).filter(r => r.status === 'gap' || r.status === 'partial')
out.push('', `## Open items at Levels 1–2 (${open.length})`, '',
  'Each has a proposed rule. Closing one = add the rule to the standard (or an exception), then update', '`asvs-map.json` and re-render.', '',
  '| ASVS | L | Status | Missing | Proposed rule |', '|---|---|---|---|---|')
for (const r of open) out.push(`| ${r.req_id} | ${r.L} | ${ICON[r.status]} | ${esc(r.note)} | ${esc(r.proposed)} |`)
out.push('', '## All requirements', '')
for (const [id, name] of chapters) {
  out.push(`### ${id} ${name}`, '', '| ASVS | L | Status | Our rules | Note |', '|---|---|---|---|---|')
  for (const r of rows.filter(x => x.chapter_id === id)) out.push(`| ${r.req_id} | ${r.L} | ${ICON[r.status] || '?'} | ${(r.rules || []).join(', ')} | ${esc(r.note)} |`)
  out.push('')
}
writeFileSync(join(here, 'ASVS-5.0.md'), out.join('\n'))
const t2 = tally(atLevel(2))
console.log(`✓ mappings/ASVS-5.0.md — L1–2: ${t2.covered} covered, ${t2.partial} partial, ${t2.gap} gap, ${t2['n/a']} n/a`)
